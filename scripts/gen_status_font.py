"""Generate packed rows and width metadata for Panel Status 10.

The source pixels are derived from Mona10 and remain under OFL-1.1.
Generation uses only the Python standard library; firmware never reads TTF.
"""

import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'scripts' / 'status10.txt'
HEADER = ROOT / 'include' / 'zmk-display-72x40' / 'display_72x40_status_font.h'


def generate():
    glyphs = {}
    lines = iter(SOURCE.read_text(encoding='utf-8').splitlines())
    for line in lines:
        if not line or line.startswith('#'):
            continue
        match = re.fullmatch(r'== (0x[0-9a-f]{2}) ([1-8])', line)
        if not match:
            raise ValueError(f'invalid glyph header: {line}')
        code, width = int(match[1], 16), int(match[2])
        if code in glyphs:
            raise ValueError(f'duplicate glyph: {code}')
        rows = [next(lines) for _ in range(10)]
        if any(len(row) != width or set(row) - {'.', '#'} for row in rows):
            raise ValueError(f'invalid pixels: {code}')
        packed = [sum(1 << (7 - x) for x, pixel in enumerate(row) if pixel == '#') for row in rows]
        glyphs[code] = (width, packed)
    if set(glyphs) != set(range(32, 127)):
        raise ValueError('the source must contain printable ASCII exactly once')
    out = ['/*', ' * Copyright (c) 2025 Monad ABXY; bitmap subset by amgskobo.',
           ' * SPDX-License-Identifier: OFL-1.1',
           ' * Panel Status 10, derived from Mona10. See licenses/mona-OFL.txt.',
           ' * Generated by scripts/gen_status_font.py; edit scripts/status10.txt.',
           ' */', '', '#pragma once', '#include <stdint.h>', '',
           '#define D72X40_STATUS_FONT_HEIGHT 10',
           'static const uint8_t d72x40_status_advance[95] = {']
    for code, (width, _) in sorted(glyphs.items()):
        out.append(f'    {width}, /* 0x{code:02x} */')
    out.extend(['};', '', 'static const uint8_t d72x40_status_rows[95][10] = {'])
    for code, (width, rows) in sorted(glyphs.items()):
        values = ', '.join(f'0x{v:02x}' for v in rows)
        out.append(f'    {{{values}}}, /* 0x{code:02x} */')
    return '\n'.join(out + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = generate()
    if args.check:
        if not HEADER.is_file() or HEADER.read_text(encoding='utf-8') != data:
            raise SystemExit('status font is stale; run scripts/gen_status_font.py')
    else:
        HEADER.write_text(data, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
