"""Turn scripts/font5x7.txt into include/zmk-display-lite/display_lite_font.h.

Each glyph becomes five column bytes. Bit r of a column is row r, the top row
being bit 0, which is how a page-tiled monochrome controller (SSD1306 and
alike) stores a column of a page. Run with --check to fail when the header is
out of date instead of rewriting it.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "font5x7.txt"
HEADER = ROOT / "include" / "zmk-display-lite" / "display_lite_font.h"

WIDTH = 5
HEIGHT = 7
SYMBOL_COUNT = 7
ASCII_FIRST = 0x20
ASCII_LAST = 0x7E


def parse(text):
    glyphs = {}
    labels = {}
    code = None
    rows = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#") and not re.fullmatch(r"[#.]{5}", line):
            continue
        header = re.fullmatch(r"==\s+(0x[0-9a-fA-F]{2})\s*(.*)", line)
        if header:
            if code is not None:
                raise SystemExit(f"line {number}: glyph 0x{code:02x} has {len(rows)} rows")
            code = int(header.group(1), 16)
            if code in glyphs:
                raise SystemExit(f"line {number}: glyph 0x{code:02x} defined twice")
            labels[code] = header.group(2).strip()
            rows = []
            continue
        if code is None:
            raise SystemExit(f"line {number}: row outside a glyph")
        if not re.fullmatch(r"[#.]{5}", line):
            raise SystemExit(f"line {number}: expected five '#'/'.' cells, got {line!r}")
        rows.append(line)
        if len(rows) == HEIGHT:
            columns = []
            for x in range(WIDTH):
                value = 0
                for y in range(HEIGHT):
                    if rows[y][x] == "#":
                        value |= 1 << y
                columns.append(value)
            glyphs[code] = columns
            code = None
    if code is not None:
        raise SystemExit(f"glyph 0x{code:02x} is incomplete")
    return glyphs, labels


def c_label(code, labels):
    if ASCII_FIRST <= code <= ASCII_LAST:
        # A backslash would continue the comment line in C.
        return "backslash" if code == 0x5C else f"'{chr(code)}'"
    return labels.get(code) or "blank"


def render(glyphs, labels):
    missing = [c for c in range(ASCII_FIRST, ASCII_LAST + 1) if c not in glyphs]
    if missing:
        raise SystemExit("missing ASCII glyphs: " + ", ".join(f"0x{c:02x}" for c in missing))
    stray = [c for c in glyphs if not (c < SYMBOL_COUNT or ASCII_FIRST <= c <= ASCII_LAST)]
    if stray:
        raise SystemExit("glyph codes outside the tables: " + ", ".join(f"0x{c:02x}" for c in stray))

    def row(code):
        cols = glyphs.get(code, [0] * WIDTH)
        body = ", ".join(f"0x{v:02x}" for v in cols)
        return f"    {{{body}}}, /* 0x{code:02x} {c_label(code, labels)} */"

    out = [
        "/*",
        " * Copyright (c) 2026 amgskobo",
        " * SPDX-License-Identifier: MIT",
        " *",
        " * Generated by scripts/gen_font.py from scripts/font5x7.txt; edit that",
        " * file and rerun the script rather than editing this one.",
        " *",
        " * Five column bytes per glyph. Bit r is row r, the top row being bit 0.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define DL_FONT_WIDTH {WIDTH}",
        f"#define DL_FONT_HEIGHT {HEIGHT}",
        f"#define DL_FONT_SYMBOL_COUNT {SYMBOL_COUNT}",
        f"#define DL_FONT_ASCII_FIRST 0x{ASCII_FIRST:02x}",
        f"#define DL_FONT_ASCII_LAST 0x{ASCII_LAST:02x}",
        "",
        "/* The module's own symbols, addressed by the control codes below 0x20. */",
        "static const uint8_t dl_font_symbols[DL_FONT_SYMBOL_COUNT][DL_FONT_WIDTH] = {",
    ]
    out += [row(code) for code in range(SYMBOL_COUNT)]
    out += [
        "};",
        "",
        "static const uint8_t",
        "    dl_font_ascii[DL_FONT_ASCII_LAST - DL_FONT_ASCII_FIRST + 1][DL_FONT_WIDTH] = {",
    ]
    out += [row(code) for code in range(ASCII_FIRST, ASCII_LAST + 1)]
    out += ["};", ""]
    return "\n".join(out)


def preview(glyphs, codes):
    for code in codes:
        cols = glyphs[code]
        print(f"0x{code:02x}")
        for y in range(HEIGHT):
            print("".join("#" if cols[x] >> y & 1 else "." for x in range(WIDTH)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the header is stale")
    parser.add_argument("--preview", metavar="TEXT", help="print TEXT's glyphs and exit")
    args = parser.parse_args()

    glyphs, labels = parse(SOURCE.read_text(encoding="utf-8"))
    if args.preview is not None:
        preview(glyphs, [ord(c) for c in args.preview])
        return 0

    header = render(glyphs, labels)
    current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else None
    if args.check:
        if current != header:
            print(f"{HEADER.relative_to(ROOT)} is out of date; run scripts/gen_font.py",
                  file=sys.stderr)
            return 1
        return 0
    if current != header:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text(header, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
