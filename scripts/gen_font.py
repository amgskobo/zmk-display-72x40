"""Turn scripts/font5x7.txt into include/zmk-display-72x40/display_72x40_font.h.

Only the fixed layout's status symbols are emitted, as native row masks.
Ordinary text uses the separate status10 font. Run with --check to fail when
the generated header is out of date instead of rewriting it.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "font5x7.txt"
HEADER = ROOT / "include" / "zmk-display-72x40" / "display_72x40_font.h"

WIDTH = 5
HEIGHT = 7
SYMBOL_COUNT = 7


def parse(text):
    glyphs = {}
    labels = {}
    code = None
    rows = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#") and not re.fullmatch(r"[#.]{5}", line):
            continue
        header = re.fullmatch(r"==\s+(0x[0-9a-fA-F]{2})\s*(.*)", line)
        if header:
            if code is not None:
                raise SystemExit(f"line {number}: glyph 0x{code:02x} has {len(rows)} rows")
            code = int(header.group(1), 16)
            if code in glyphs:
                raise SystemExit(f"line {number}: glyph 0x{code:02x} defined twice")
            labels[code] = header.group(2).strip()
            rows = []
            continue
        if code is None:
            raise SystemExit(f"line {number}: row outside a glyph")
        if not re.fullmatch(r"[#.]{5}", line):
            raise SystemExit(f"line {number}: expected five '#'/'.' cells, got {line!r}")
        rows.append(line)
        if len(rows) == HEIGHT:
            columns = []
            for x in range(WIDTH):
                value = 0
                for y in range(HEIGHT):
                    if rows[y][x] == "#":
                        value |= 1 << y
                columns.append(value)
            glyphs[code] = columns
            code = None
    if code is not None:
        raise SystemExit(f"glyph 0x{code:02x} is incomplete")
    return glyphs, labels


def render(glyphs, labels):
    missing = [c for c in range(1, SYMBOL_COUNT) if c not in glyphs]
    if missing:
        raise SystemExit("missing symbol glyphs: " + ", ".join(f"0x{c:02x}" for c in missing))
    if any(c >= SYMBOL_COUNT for c in glyphs):
        raise SystemExit("glyph code outside the symbol table")
    if any(glyphs.get(0, [0] * WIDTH)):
        raise SystemExit("symbol zero must be blank")
    out = [
        "/* Copyright (c) 2026 amgskobo",
        " * SPDX-License-Identifier: MIT",
        " * Generated by scripts/gen_font.py from scripts/font5x7.txt.",
        " * Native row masks: bit seven is the left edge.",
        " */", "", "#pragma once", "", "#include <stdint.h>", "",
        f"#define D72X40_FONT_WIDTH {WIDTH}",
        f"#define D72X40_FONT_HEIGHT {HEIGHT}",
        f"#define D72X40_FONT_SYMBOL_COUNT {SYMBOL_COUNT}", "",
        "static const uint8_t d72x40_symbol_rows[D72X40_FONT_SYMBOL_COUNT][D72X40_FONT_HEIGHT] = {",
    ]
    for code in range(SYMBOL_COUNT):
        columns = glyphs.get(code, [0] * WIDTH)
        values = [sum(((columns[x] >> y) & 1) << (7 - x) for x in range(WIDTH)) for y in range(HEIGHT)]
        body = ", ".join(f"0x{v:02x}" for v in values)
        label = labels.get(code) or "blank"
        out.append(f"    {{{body}}}, /* 0x{code:02x} {label} */")
    return "\n".join(out + ["};", ""])


def preview(glyphs, codes):
    for code in codes:
        cols = glyphs.get(code, [0] * WIDTH if code == 0 else None)
        if cols is None:
            raise SystemExit(f"0x{code:02x} is not a status symbol; ordinary text uses Panel Status 10")
        print(f"0x{code:02x}")
        for y in range(HEIGHT):
            print("".join("#" if cols[x] >> y & 1 else "." for x in range(WIDTH)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the header is stale")
    parser.add_argument("--preview", metavar="TEXT", help="print TEXT's glyphs and exit")
    args = parser.parse_args()

    glyphs, labels = parse(SOURCE.read_text(encoding="utf-8"))
    if args.preview is not None:
        preview(glyphs, [ord(c) for c in args.preview])
        return 0

    header = render(glyphs, labels)
    current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else None
    if args.check:
        if current != header:
            print(f"{HEADER.relative_to(ROOT)} is out of date; run scripts/gen_font.py",
                  file=sys.stderr)
            return 1
        return 0
    if current != header:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text(header, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
